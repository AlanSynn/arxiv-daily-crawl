def update_paper_links(filename):
    '''
    weekly update paper links in json file
    '''
    def parse_arxiv_string(s):
        parts = s.split("|")
        date = parts[1].strip()
        title = parts[2].strip()
        authors = parts[3].strip()
        arxiv_id = parts[4].strip()
        code = parts[5].strip()

        # Handle cases where arxiv_id might contain @ symbol
        if '@' in arxiv_id:
            match = re.search(r'\[@(.*?)\]', arxiv_id)
            if match:
                arxiv_id = match.group(1)
        else:
            arxiv_id = re.sub(r'\[(.*?)\]', r'\1', arxiv_id)

        arxiv_id = re.sub(r'v\d+', '', arxiv_id)
        return date,title,authors,arxiv_id,code

    with open(filename,"r") as f:
        content = f.read()
        if not content:
            m = {}
        else:
            m = json.loads(content)

        json_data = m.copy()

        for keywords,v in json_data.items():
            logging.info(f'keywords = {keywords}')
            for paper_id,contents in v.items():
                contents = str(contents)

                update_time, paper_title, paper_first_author, paper_url, code_url = parse_arxiv_string(contents)

                contents = "|{}|{}|{}|{}|{}|\n".format(update_time,paper_title,paper_first_author,paper_url,code_url)
                json_data[keywords][paper_id] = str(contents)
                logging.info(f'paper_id = {paper_id}, contents = {contents}')

                valid_link = False if '|null|' in contents else True
                if valid_link:
                    continue
                try:
                    code_url = base_url + paper_id #TODO
                    r = requests.get(code_url).json()
                    repo_url = None
                    if "official" in r and r["official"]:
                        repo_url = r["official"]["url"]
                        if repo_url is not None:
                            # Replace [id] with [@id] in the paper_url field
                            if '[' in contents and ']' in contents:
                                paper_url_part = paper_url
                                if not paper_url_part.startswith('@'):
                                    paper_url_part = paper_url_part.replace('[', '[@')
                                    new_cont = contents.replace('|null|',f'|**[link]({repo_url})**|')
                                    new_cont = new_cont.replace(paper_url, paper_url_part)
                                else:
                                    new_cont = contents.replace('|null|',f'|**[link]({repo_url})**|')
                            else:
                                new_cont = contents.replace('|null|',f'|**[link]({repo_url})**|')

                            logging.info(f'ID = {paper_id}, contents = {new_cont}')
                            json_data[keywords][paper_id] = str(new_cont)

                except Exception as e:
                    logging.error(f"exception: {e} with id: {paper_id}")
        # dump to json file
        with open(filename,"w") as f:
            json.dump(json_data,f)

def update_json_file(filename, data_dict, create_new=False):
    '''
    daily update json file using data_dict
    if create_new is True, create a new file instead of updating existing one
    '''
    # Ensure the directory exists
    directory = os.path.dirname(filename)
    if directory and not os.path.exists(directory):
        os.makedirs(directory)
        logging.info(f"Created directory: {directory}")

    if create_new or not os.path.exists(filename) or os.path.getsize(filename) == 0:
        # Create new file
        json_data = {}
        for data in data_dict:
            for keyword in data.keys():
                papers = data[keyword]
                if keyword in json_data.keys():
                    json_data[keyword].update(papers)
                else:
                    json_data[keyword] = papers

        with open(filename, "w") as f:
            json.dump(json_data, f)
        logging.info(f"Created new JSON file: {filename}")
    else:
        # Update existing file
        try:
            with open(filename, "r") as f:
                content = f.read()
                if not content:
                    m = {}
                else:
                    m = json.loads(content)
        except (FileNotFoundError, json.JSONDecodeError) as e:
            logging.warning(f"Error reading {filename}: {e}. Creating a new file.")
            m = {}

        json_data = m.copy()

        # Update papers in each keywords
    for data in data_dict:
        for keyword in data.keys():
            papers = data[keyword]

            if keyword in json_data.keys():
                json_data[keyword].update(papers)
            else:
                json_data[keyword] = papers

        with open(filename, "w") as f:
            json.dump(json_data, f)
        logging.info(f"Updated existing JSON file: {filename}")

    return json_data

def json_to_md(filename, md_filename,
               task = '',
               to_web = False,
               use_title = True,
               use_tc = True,
               show_badge = True,
               use_b2t = True,
               create_new=False):
    """
    @param filename: str
    @param md_filename: str
    @param create_new: bool, if True, create new file instead of updating existing
    @return None
    """
    def pretty_math(s:str) -> str:
        ret = ''
        match = re.search(r"\$.*\$", s)
        if match == None:
            return s
        math_start,math_end = match.span()
        space_trail = space_leading = ''
        if s[:math_start][-1] != ' ' and '*' != s[:math_start][-1]: space_trail = ' '
        if s[math_end:][0] != ' ' and '*' != s[math_end:][0]: space_leading = ' '
        ret += s[:math_start]
        ret += f'{space_trail}${match.group()[1:-1].strip()}${space_leading}'
        ret += s[math_end:]
        return ret

    # Ensure the directory exists
    directory = os.path.dirname(md_filename)
    if directory and not os.path.exists(directory):
        os.makedirs(directory)
        logging.info(f"Created directory: {directory}")

    DateNow = datetime.date.today()
    DateNow = str(DateNow)
    DateNow = DateNow.replace('-','.')

    # Check if JSON file exists, if not create empty dict
    if not os.path.exists(filename):
        logging.warning(f"JSON file {filename} not found. Creating an empty file.")
        with open(filename, "w") as f:
            json.dump({}, f)
        data = {}
    else:
        try:
            with open(filename,"r") as f:
                content = f.read()
                if not content:
                    data = {}
                else:
                    data = json.loads(content)
        except json.JSONDecodeError:
            logging.warning(f"Error parsing JSON from {filename}. Using empty data.")
            data = {}

    # Create or overwrite the MD file
    with open(md_filename,"w") as f:
        if (use_title == True) and (to_web == True):
            f.write("---\n" + "layout: default\n" + "---\n\n")

        if show_badge == True:
            f.write(f"[![Contributors][contributors-shield]][contributors-url]\n")
            f.write(f"[![Forks][forks-shield]][forks-url]\n")
            f.write(f"[![Stargazers][stars-shield]][stars-url]\n")
            f.write(f"[![Issues][issues-shield]][issues-url]\n\n")

        if use_title == True:
            f.write("## 📚 Updated on " + DateNow + "\n")
        else:
            f.write("> 📚 Updated on " + DateNow + "\n")

        # TODO: add usage
        f.write("> 📖 Usage instructions: [here](./docs/README.md#usage)\n\n")

        #Add: table of contents
        if use_tc == True:
            f.write("<details>\n")
            f.write("  <summary>Table of Contents</summary>\n")
            f.write("  <ol>\n")
            for keyword in data.keys():
                day_content = data[keyword]
                if not day_content:
                    continue
                kw = keyword.replace(' ','-')
                f.write(f"    <li><a href=#{kw}>{keyword}</a></li>\n")
            f.write("  </ol>\n")
            f.write("</details>\n\n")

        for keyword in data.keys():
            day_content = data[keyword]
            if not day_content:
                continue
            # the head of each part
            f.write(f"## {keyword}\n\n")

            if use_title == True :
                if to_web == False:
                    f.write("|Publish Date|Title|Authors|arXiv|Code|\n" + "|---|---|---|---|---|\n")
                else:
                    f.write("| Publish Date | Title | Authors | arXiv | Code |\n")
                    f.write("|:---------|:-----------------------|:---------|:------|:------|\n")

            # sort papers by date
            day_content = sort_papers(day_content)

            for _,v in day_content.items():
                if v is not None:
                    f.write(pretty_math(v)) # make latex pretty

            f.write(f"\n")

            #Add: back to top
            if use_b2t:
                top_info = f"#Updated on {DateNow}"
                top_info = top_info.replace(' ','-').replace('.','')
                f.write(f"<p align=right>(<a href={top_info}>back to top</a>)</p>\n\n")

        if show_badge == True:
            # we don't like long string, break it!
            f.write((f"[contributors-shield]: https://img.shields.io/github/"
                     f"contributors/AlanSynn/daily-arxiv.svg?style=for-the-badge\n"))
            f.write((f"[contributors-url]: https://github.com/AlanSynn/"
                     f"daily-arxiv/graphs/contributors\n"))
            f.write((f"[forks-shield]: https://img.shields.io/github/forks/AlanSynn/"
                     f"daily-arxiv.svg?style=for-the-badge\n"))
            f.write((f"[forks-url]: https://github.com/AlanSynn/"
                     f"daily-arxiv/network/members\n"))
            f.write((f"[stars-shield]: https://img.shields.io/github/stars/AlanSynn/"
                     f"daily-arxiv.svg?style=for-the-badge\n"))
            f.write((f"[stars-url]: https://github.com/AlanSynn/"
                     f"daily-arxiv/stargazers\n"))
            f.write((f"[issues-shield]: https://img.shields.io/github/issues/AlanSynn/"
                     f"daily-arxiv.svg?style=for-the-badge\n"))
            f.write((f"[issues-url]: https://github.com/AlanSynn/"
                     f"daily-arxiv/issues\n\n"))

    logging.info(f"{task} finished: {md_filename}")

def send_email(email_to, email_subject, email_body, config):
    """Send email with daily paper updates

    Args:
        email_to: Recipient email address
        email_subject: Email subject
        email_body: Email body content (HTML format)
        config: Configuration with email settings
    """
    if not config.get('email_settings', {}).get('enabled', False):
        logging.warning("Email settings not configured or disabled")
        return False

    email_settings = config.get('email_settings', {})
    smtp_server = email_settings.get('smtp_server')
    smtp_port = email_settings.get('smtp_port', 587)
    smtp_user = email_settings.get('smtp_user')
    smtp_password = email_settings.get('smtp_password')

    if not all([smtp_server, smtp_user, smtp_password]):
        logging.error("SMTP settings incomplete. Check your config file.")
        return False

    msg = MIMEMultipart('alternative')
    msg['Subject'] = email_subject
    msg['From'] = smtp_user
    msg['To'] = email_to

    # Create both plain text and HTML versions for email clients that don't support HTML
    text_part = MIMEText("This email requires HTML support to view properly.", 'plain')
    html_part = MIMEText(email_body, 'html')

    msg.attach(text_part)
    msg.attach(html_part)

    try:
        server = smtplib.SMTP(smtp_server, smtp_port)
        server.ehlo()
        server.starttls()
        server.login(smtp_user, smtp_password)
        server.send_message(msg)
        server.quit()
        logging.info(f"Email sent successfully to {email_to}")
        return True
    except Exception as e:
        logging.error(f"Failed to send email: {e}")
        return False

